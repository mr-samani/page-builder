#!/usr/bin/env node
/**
 * SVG → TypeScript icon generator.
 *
 *   node scripts/generate-icons.mjs [--src <dir>] [--out <dir>] [--keep-colors] [--check]
 *
 * - Reads every *.svg under --src (recursively).
 * - Optimizes with SVGO (strips metadata/dimensions, converts colors to currentColor,
 *   prefixes ids so inline icons never collide).
 * - Emits one tree-shakable TS module per icon + barrel + name union type + ALL_ICONS.
 * - Sanitizes at build time (element/attribute allow-list) – the runtime renderer
 *   applies the same allow-list again (defense in depth).
 *
 * Conventions:
 *   grip-dots.svg        → name 'grip-dots', export `gripDots`
 *   arrows/up.svg        → name 'arrows-up', export `arrowsUp`
 *   logo.color.svg       → name 'logo', original colors are KEPT (multi-color icon)
 *   3d-box.svg           → export `icon3dBox` (identifiers can't start with a digit)
 *
 * --check : generate in memory and fail (exit 1) if the files on disk differ. Use in CI.
 */
import { readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { optimize } from 'svgo';
import { parse } from 'svgson';

const { values: args } = parseArgs({
  options: {
    src: { type: 'string', default: 'projects/ngx-page-builder/icons' },
    out: { type: 'string', default: 'projects/ngx-page-builder/icons/generated' },
    types: { type: 'string', default: '../icon-definition' }, // import path of IconDefinition, relative to --out
    'keep-colors': { type: 'boolean', default: false },
    check: { type: 'boolean', default: false },
  },
});

// Keep in sync with icon.component.ts
const ALLOWED_TAGS = new Set([
  'path',
  'circle',
  'ellipse',
  'rect',
  'line',
  'polyline',
  'polygon',
  'g',
  'defs',
  'clipPath',
  'mask',
  'linearGradient',
  'radialGradient',
  'stop',
]);
const ROOT_KEEP = [
  'fill',
  'stroke',
  'stroke-width',
  'stroke-linecap',
  'stroke-linejoin',
  'stroke-miterlimit',
  'fill-rule',
  'clip-rule',
];
const RESERVED = new Set([
  'break',
  'case',
  'catch',
  'class',
  'const',
  'continue',
  'debugger',
  'default',
  'delete',
  'do',
  'else',
  'enum',
  'export',
  'extends',
  'false',
  'finally',
  'for',
  'function',
  'if',
  'import',
  'in',
  'instanceof',
  'new',
  'null',
  'return',
  'super',
  'switch',
  'this',
  'throw',
  'true',
  'try',
  'typeof',
  'var',
  'void',
  'while',
  'with',
  'yield',
  'let',
  'static',
  'await',
  'async',
  'interface',
  'package',
  'private',
  'protected',
  'public',
  'implements',
  'type',
  'undefined',
  'arguments',
  'eval',
]);
const HEADER = '/* @generated by scripts/generate-icons.mjs — DO NOT EDIT. */\n';
const URL_REF = /^url\(#[\w.:-]+\)$/;

const srcDir = path.resolve(args.src);
const outDir = path.resolve(args.out);

// ───────────────────────── helpers ─────────────────────────
async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) files.push(...(await walk(full)));
    else if (e.isFile() && e.name.toLowerCase().endsWith('.svg')) files.push(full);
  }
  return files.sort();
}

function toKebab(s) {
  return s
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function toIdentifier(kebab) {
  const parts = kebab.split('-').filter(Boolean);
  const pascal = parts.map((p) => p[0].toUpperCase() + p.slice(1)).join('');
  const camel = pascal[0].toLowerCase() + pascal.slice(1);
  return /^\d/.test(camel) || RESERVED.has(camel) ? `icon${pascal}` : camel;
}

function q(s) {
  return `'${String(s)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/[\r\n]+/g, ' ')}'`;
}
const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : q(k));
const attrsLit = (a) => {
  const e = Object.entries(a);
  return e.length ? `{ ${e.map(([k, v]) => `${key(k)}: ${q(v)}`).join(', ')} }` : '{}';
};
const nodeLit = ([tag, a, ch]) =>
  ch?.length ? `[${q(tag)}, ${attrsLit(a)}, [${ch.map(nodeLit).join(', ')}]]` : `[${q(tag)}, ${attrsLit(a)}]`;

function isSafeAttr(name, value) {
  const n = name.toLowerCase();
  if (n.startsWith('on') || n === 'style' || n === 'class' || n === 'href') return false;
  if (n.startsWith('xlink') || n.startsWith('xmlns') || n.startsWith('data-')) return false;
  if (/javascript:/i.test(value)) return false;
  if (value.includes('url(') && !URL_REF.test(value.trim())) return false;
  return true;
}

function toNode(el, file) {
  if (el.type !== 'element') return null;
  if (!ALLOWED_TAGS.has(el.name)) {
    console.warn(`  ⚠ ${file}: <${el.name}> is not allowed and was removed`);
    return null;
  }
  const attrs = {};
  for (const [k, v] of Object.entries(el.attributes)) {
    if (isSafeAttr(k, v)) attrs[k] = v;
    else if (k !== 'class' && k !== 'style') console.warn(`  ⚠ ${file}: attribute "${k}" was removed`);
  }
  const children = el.children.map((c) => toNode(c, file)).filter(Boolean);
  return children.length ? [el.name, attrs, children] : [el.name, attrs];
}

async function convert(file, name, keepColors) {
  const raw = await readFile(file, 'utf8');

  // pass 1: structural optimization (multipass)
  const pass1 = optimize(raw, {
    path: file,
    multipass: true,
    plugins: [
      {
        name: 'preset-default',
        params: {
          overrides: {
            convertColors: keepColors ? {} : { currentColor: true },
          },
        },
      },
      'convertStyleToAttrs',
      'removeDimensions',
      { name: 'removeAttrs', params: { attrs: ['data-.*', 'class'] } },
    ],
  });

  // pass 2: ids unique per icon (must run once, not multipass)
  const pass2 = optimize(pass1.data, {
    path: file,
    plugins: [{ name: 'prefixIds', params: { prefix: name, delim: '-' } }],
  });

  const root = await parse(pass2.data);
  if (root.name !== 'svg') throw new Error(`${file}: root element is not <svg>`);
  const viewBox = root.attributes.viewBox;
  if (!viewBox) throw new Error(`${file}: missing viewBox (and no width/height to derive it from)`);

  const attrs = {};
  for (const k of ROOT_KEEP) if (root.attributes[k] !== undefined) attrs[k] = root.attributes[k];

  const nodes = root.children.map((c) => toNode(c, file)).filter(Boolean);
  if (!nodes.length) throw new Error(`${file}: no renderable content after sanitizing`);
  return { viewBox, attrs, nodes };
}

// ───────────────────────── main ─────────────────────────
if (!existsSync(srcDir)) {
  console.error(`✖ Source directory not found: ${srcDir}\n  Use --src <dir>`);
  process.exit(1);
}

const files = await walk(srcDir);
if (!files.length) {
  console.error(`✖ No .svg files found in ${srcDir}`);
  process.exit(1);
}

/** @type {Map<string,string>} relative file name → content */
const output = new Map();
/** @type {{name:string, id:string}[]} */
const icons = [];
const seenNames = new Map();
const seenIds = new Map();

for (const file of files) {
  const rel = path.relative(srcDir, file).replace(/\\/g, '/');
  const withoutExt = rel.replace(/\.svg$/i, '');
  const keepColors = args['keep-colors'] || /\.color$/i.test(withoutExt);
  const name = toKebab(
    withoutExt
      .replace(/\.color$/i, '')
      .split('/')
      .join('-'),
  );
  const id = toIdentifier(name);

  if (seenNames.has(name)) throw new Error(`Duplicate icon name "${name}": ${rel} and ${seenNames.get(name)}`);
  if (seenIds.has(id)) throw new Error(`Duplicate identifier "${id}": ${rel} and ${seenIds.get(id)}`);
  seenNames.set(name, rel);
  seenIds.set(id, rel);

  try {
    const { viewBox, attrs, nodes } = await convert(file, name, keepColors);
    const body = [
      `export const ${id}: IconDefinition = {`,
      `  name: ${q(name)},`,
      `  viewBox: ${q(viewBox)},`,
      ...(Object.keys(attrs).length ? [`  attrs: ${attrsLit(attrs)},`] : []),
      `  nodes: [`,
      ...nodes.map((n) => `    ${nodeLit(n)},`),
      `  ],`,
      `};`,
      '',
    ].join('\n');
    output.set(`${name}.ts`, `${HEADER}import type { IconDefinition } from '${args.types}';\n\n${body}`);
    icons.push({ name, id });
  } catch (err) {
    console.error(`✖ ${rel}: ${err.message}`);
    process.exitCode = 1;
  }
}
if (process.exitCode) process.exit(1);

icons.sort((a, b) => a.name.localeCompare(b.name));

output.set('index.ts', HEADER + icons.map((i) => `export { ${i.id} } from './${i.name}';`).join('\n') + '\n');
output.set(
  'icon-names.ts',
  `${HEADER}/** Union of all built-in icon names (type only – zero runtime cost). */\nexport type NgxIconName =\n${icons
    .map((i) => `  | ${q(i.name)}`)
    .join('\n')};\n`,
);
output.set(
  'all.ts',
  `${HEADER}import type { IconDefinition } from '${args.types}';\n${icons
    .map((i) => `import { ${i.id} } from './${i.name}';`)
    .join(
      '\n',
    )}\n\n/**\n * Every built-in icon. Importing this defeats tree-shaking – use only for\n * playgrounds, Storybook galleries or when you really need all of them.\n */\nexport const ALL_ICONS: readonly IconDefinition[] = [\n${icons
    .map((i) => `  ${i.id},`)
    .join('\n')}\n];\n`,
);

// ───────────────────────── write / check ─────────────────────────
const existing = new Map();
if (existsSync(outDir)) {
  for (const f of await readdir(outDir)) {
    if (!f.endsWith('.ts')) continue;
    const content = await readFile(path.join(outDir, f), 'utf8');
    if (content.includes('@generated')) existing.set(f, content);
  }
}

if (args.check) {
  const stale = [];
  for (const [f, c] of output) if (existing.get(f) !== c) stale.push(f);
  for (const f of existing.keys()) if (!output.has(f)) stale.push(f);
  if (stale.length) {
    console.error(`✖ Generated icons are out of date (${stale.length} file(s)). Run: npm run icons`);
    process.exit(1);
  }
  console.log(`✔ ${icons.length} icons up to date`);
  process.exit(0);
}

await mkdir(outDir, { recursive: true });
for (const [f, c] of output) {
  if (existing.get(f) !== c) await writeFile(path.join(outDir, f), c, 'utf8');
}
for (const f of existing.keys()) {
  if (!output.has(f)) await rm(path.join(outDir, f)); // stale icon removed from source
}
console.log(`✔ ${icons.length} icons generated → ${path.relative(process.cwd(), outDir)}`);
